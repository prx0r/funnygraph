def main() -> None:
    n = n_skip = 0
    for d in sorted(COMEDIANS.iterdir()):
        g = d / "comedian-graph.json"
        if not g.exists():
            continue
        cid = d.name
        if cid not in GEN:
            n_skip += 1
            continue
        gen_id, scene, note = GEN[cid]
        if "placeholder" in note:
            n_skip += 1
            continue
        j = json.loads(g.read_text())
        j["generation"] = {"id": gen_id, **GENS[gen_id],
                           "scene": scene, "breakthrough": note}
        g.write_text(json.dumps(j, indent=2) + "\n", encoding="utf-8")
        n += 1
    print(f"generations: {n} assigned, {n_skip} skipped (no entry/placeholder)")
    # generation census
    from collections import Counter
    c = Counter()
    for d in sorted(COMEDIANS.iterdir()):
        g = d / "comedian-graph.json"
        if not g.exists():
            continue
        j = json.loads(g.read_text())
        if j.get("generation"):
            c[j["generation"]["id"]] += 1
    print("census:", dict(c))


if __name__ == "__main__":
    main()
